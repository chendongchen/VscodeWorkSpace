import numpy as np
import matplotlib.pyplot as plt
import sympy as sp

esps = {1e-6, 1e-8, 1e-10}
x = sp.symbols('x')
p = 1

for i in range(1,11):
    p = p*(x -i)

print(sp.expand(p))

for esp in esps:
    numeric_root =  sp.roots(p + esp*x**9)
    print("esp = ", esp)
    print("roots = ", numeric_root)

